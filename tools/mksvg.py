#!/usr/bin/env python3
"""Pack assets/icons/*.svg into kernel/svgdata.kc (one string constant per icon, minified).
Usage: mksvg.py assets/icons kernel/svgdata.kc"""
import sys, os, re
src, out = sys.argv[1], sys.argv[2]
order = ['logo','terminal','notes','paint','calc','info','files','cal','clock','snake','mines','monitor','browser','builder','theme','fonts','studio3d', '', 'settings'] + [''] * 13 + ['d%d' % i for i in range(10)]   # index = app kind; 32.. digits
# app kind -> icon name (kinds: 1 term 2 notes 3 paint 4 calc 5 info 6 files 7 cal 8 clock 9 snake 10 mines 11 mon 12 web 13 bld 14 theme)
lines = ["// svgdata.kc -- GENERATED by tools/mksvg.py from assets/icons/*.svg (do not edit)", ""]
glyphs = [l.strip() for l in open(os.path.join(os.path.dirname(src.rstrip('/')), 'glyphs', 'ORDER.txt')) if l.strip()]
lines.append("// monochrome UI glyphs (assets/glyphs): kinds 64.. -- draw them tinted with svg_tint()")
for gi, gname in enumerate(glyphs):
    lines.append("const G_%s = %d;" % (gname.upper().replace('-', '_'), 64 + gi))
lines.append("")
lines.append("fn svg_src(kind: int) -> *u8 {")
for i, name in enumerate(order):
    if name == '':
        continue
    s = open(os.path.join(src, name + '.svg')).read()
    s = re.sub(r'\s+', ' ', s).strip().replace('> <', '><')
    assert '"' not in s and '\\' not in s, name
    lines.append(f'    if (kind == {i}) {{ return "{s}"; }}')
for gi, gname in enumerate(glyphs):
    g = re.sub(r'\s+', ' ', open(os.path.join(os.path.dirname(src.rstrip('/')), 'glyphs', gname + '.svg')).read()).strip()
    assert '"' not in g
    lines.append(f'    if (kind == {64 + gi}) {{ return "{g}"; }}')
lines.append('    return "";')
lines.append("}")
open(out, 'w').write("\n".join(lines) + "\n")
print(f"mksvg: {len(order)} icons + {len(glyphs)} glyphs -> {out}")
