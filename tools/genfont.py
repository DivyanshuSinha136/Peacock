#!/usr/bin/env python3
"""genfont.py -- regenerate kernel/font.kc: DejaVu Sans Mono rendered anti-aliased into 8x16 cells (ASCII 32..126),
4-bit coverage, two pixels per byte (high nibble = left pixel).  Usage: python3 tools/genfont.py [path-to-DejaVuSansMono.ttf]
DejaVu fonts: Bitstream Vera licence (free to use, embed and redistribute) -- see docs/LICENSES.md."""
import sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZE = 13
f = ImageFont.truetype(path, SIZE)
asc, desc = f.getmetrics()
top = (16 - (asc + desc)) // 2 + 1            # vertical placement inside the 16-row cell
out = []
for c in range(32, 127):
    im = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(im)
    adv = f.getlength(chr(c))
    d.text((round((8 - adv) / 2) if False else 0, top), chr(c), fill=255, font=f)
    px = im.load()
    for y in range(16):
        for x in range(0, 8, 2):
            a = round(px[x, y] / 17); b = round(px[x + 1, y] / 17)
            out.append((a << 4) | b)
lines = []
for i in range(0, len(out), 16):
    lines.append("    " + ", ".join("0x%02X" % v for v in out[i:i + 16]) + ",")
src = """// font.kc -- 8x16 anti-aliased font, ASCII 32..126: 4-bit coverage per pixel, two pixels per byte (high nibble = left),
// 4 bytes per row, 64 bytes per glyph.  Generated by tools/genfont.py from DejaVu Sans Mono (Bitstream Vera licence).
// Author of Peacock: Divyanshu Sinha (MIT License)

const FONT_W = 8;
const FONT_H = 16;

var font_aa: u8[%d] = [
%s
];
""" % (len(out), "\n".join(lines))
open("kernel/font.kc", "w").write(src)
print("glyphs:", len(out) // 64, "bytes:", len(out))
