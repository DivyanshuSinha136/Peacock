#!/usr/bin/env python3
"""mkpeacock.py -- turn assets/peacock.jpg into kernel/peacockicon.kc: a 48x48 RGBA icon (hex string) for the Start button.
The flat grey backdrop is removed by flood-filling from the borders, so the artwork keeps its own light areas."""
import sys
from collections import deque
from PIL import Image

N = 48
src = sys.argv[1] if len(sys.argv) > 1 else 'assets/peacock.jpg'
out = sys.argv[2] if len(sys.argv) > 2 else 'kernel/peacockicon.kc'
im = Image.open(src).convert('RGB')
w, h = im.size
px = im.load()
bg = px[4, 4]
def dist(c): return max(abs(c[0]-bg[0]), abs(c[1]-bg[1]), abs(c[2]-bg[2]))
alpha = [[255]*w for _ in range(h)]
seen = [[False]*w for _ in range(h)]
q = deque()
for x in range(w):
    for y in (0, h-1): q.append((x, y)); seen[y][x] = True
for y in range(h):
    for x in (0, w-1):
        if not seen[y][x]: q.append((x, y)); seen[y][x] = True
while q:
    x, y = q.popleft()
    d = dist(px[x, y])
    if d > 26: continue
    alpha[y][x] = 0 if d < 12 else int((d - 12) * 255 / 14)          # soft edge
    for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
        nx, ny = x+dx, y+dy
        if 0 <= nx < w and 0 <= ny < h and not seen[ny][nx]:
            seen[ny][nx] = True; q.append((nx, ny))
rgba = Image.new('RGBA', (w, h))
rp = rgba.load()
for y in range(h):
    for x in range(w):
        r, g, b = px[x, y]; rp[x, y] = (r, g, b, alpha[y][x])
bbox = rgba.getchannel('A').point(lambda a: 255 if a > 40 else 0).getbbox()
rgba = rgba.crop(bbox)
cw, ch = rgba.size
side = max(cw, ch)
sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
sq.paste(rgba, ((side-cw)//2, (side-ch)//2))
# premultiply before resampling so edges do not pick up the backdrop colour
pm = sq.copy(); pp = pm.load()
for y in range(side):
    for x in range(side):
        r, g, b, a = pp[x, y]; pp[x, y] = (r*a//255, g*a//255, b*a//255, a)
small = pm.resize((N, N), Image.LANCZOS)
sp = small.load()
hexs = []
for y in range(N):
    for x in range(N):
        r, g, b, a = sp[x, y]
        if a > 0: r, g, b = min(255, r*255//a), min(255, g*255//a), min(255, b*255//a)
        hexs.append('%02x%02x%02x%02x' % (r, g, b, a))
data = ''.join(hexs)
with open(out, 'w') as f:
    f.write('// peacockicon.kc -- GENERATED by tools/mkpeacock.py from assets/peacock.jpg. Do not edit.\n')
    f.write('// The Start button icon: %dx%d RGBA, hex encoded.\n\n' % (N, N))
    f.write('const PK_N = %d;\n' % N)
    CH = 512
    chunks = [data[i:i+CH] for i in range(0, len(data), CH)]
    f.write('const PK_CHUNK = %d;\nconst PK_CHUNKS = %d;\n' % (CH, len(chunks)))
    f.write('/// piece `i` of the hex-encoded icon (the compiler dislikes one huge string literal)\n')
    f.write('fn pk_piece(i: int) -> *u8 {\n')
    for i, c in enumerate(chunks):
        f.write('    if (i == %d) { return "%s"; }\n' % (i, c))
    f.write('    return "";\n}\n')
print('mkpeacock: %dx%d icon, %d bytes of source' % (N, N, len(data)))
