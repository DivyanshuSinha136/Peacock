#!/usr/bin/env python3
"""gencursor.py -- regenerate kernel/cursor.kc: anti-aliased arrow / hand / text-beam mouse pointers with a soft shadow.
Each cursor is 20x26 pixels, 2 bytes per pixel (grey value, alpha)."""
from PIL import Image, ImageDraw, ImageFilter, ImageChops
SS = 8; W, H = 20, 26
def canvas(): return Image.new("L", (W * SS, H * SS), 0)
def poly(d, pts): d.polygon([(x * SS, y * SS) for x, y in pts], fill=255)
def rrect(d, x0, y0, x1, y1, r): d.rounded_rectangle([x0 * SS, y0 * SS, x1 * SS, y1 * SS], radius=r * SS, fill=255)
def dilate(m, px): return m.filter(ImageFilter.MaxFilter(px))
def render(mask, fill, edge):
    shadow = ImageChops.offset(mask, int(1.2 * SS), int(1.6 * SS)); shadow = dilate(shadow, 5).filter(ImageFilter.GaussianBlur(1.1 * SS))
    outline = dilate(mask, 13)
    img = Image.new("RGBA", mask.size, (0, 0, 0, 0))
    sh = Image.new("RGBA", mask.size, (0, 0, 0, 255)); sh.putalpha(shadow.point(lambda v: int(v * 0.35)))
    img = Image.alpha_composite(img, sh)
    e = Image.new("RGBA", mask.size, (edge, edge, edge, 255)); e.putalpha(outline)
    img = Image.alpha_composite(img, e)
    f = Image.new("RGBA", mask.size, (fill, fill, fill, 255)); f.putalpha(mask)
    img = Image.alpha_composite(img, f)
    return img.resize((W, H), Image.BOX)
# arrow: tip at (3,3)
m = canvas(); d = ImageDraw.Draw(m)
poly(d, [(3, 3), (3, 20), (7.2, 16.2), (10, 22.5), (12.6, 21.4), (9.9, 15.2), (15.4, 15.2)])
arrow = render(m, 255, 24)
# hand: fingertip at (9,3)
m = canvas(); d = ImageDraw.Draw(m)
rrect(d, 7.2, 3, 11.2, 14, 2); rrect(d, 4.5, 11, 16.5, 21.5, 3.2)
rrect(d, 11, 9.5, 13.4, 14, 1.2); rrect(d, 13.2, 10.5, 15.6, 14.5, 1.2); rrect(d, 15.4, 11.5, 17.4, 15, 1)
rrect(d, 2, 12, 6.5, 17, 2)
hand = render(m, 255, 24)
# text beam: centre at (10,13); dark beam with a white halo
m = canvas(); d = ImageDraw.Draw(m)
rrect(d, 9.4, 5, 10.8, 21, 0.4); rrect(d, 6.4, 4.4, 13.8, 5.8, 0.5); rrect(d, 6.4, 20.2, 13.8, 21.6, 0.5)
beam = render(m, 24, 255)
data = []
for im in (arrow, hand, beam):
    px = im.load()
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            data += [r, a]
rows = ["    " + ", ".join("%d" % v for v in data[i:i + 40]) + "," for i in range(0, len(data), 40)]
src = """// cursor.kc -- anti-aliased mouse pointers (arrow, hand, text beam) with soft shadows.  Generated by tools/gencursor.py.
// 20x26 pixels each, 2 bytes per pixel (grey, alpha).  Author of Peacock: Divyanshu Sinha (MIT License)

const CUR_W = 20; const CUR_H = 26;
const CUR_ARROW = 0; const CUR_HAND = 1; const CUR_BEAM = 2;

var cursor_img: u8[%d] = [
%s
];

fn cur_hot_x(kind: int) -> int { if (kind == CUR_HAND) { return 9; } if (kind == CUR_BEAM) { return 10; } return 3; }
fn cur_hot_y(kind: int) -> int { if (kind == CUR_BEAM) { return 13; } return 3; }

/// draw the pointer of the given kind with its hot spot at (x, y)
fn draw_cursor(x: int, y: int, kind: int) {
    let ox = x - cur_hot_x(kind); let oy = y - cur_hot_y(kind);
    let base = kind * CUR_W * CUR_H * 2;
    var r = 0;
    while (r < CUR_H) {
        let yy = oy + r;
        if (yy >= clip_y0 && yy < clip_y1) {
            var c = 0;
            while (c < CUR_W) {
                let xx = ox + c;
                if (xx >= clip_x0 && xx < clip_x1) {
                    let i = base + (r * CUR_W + c) * 2;
                    let a = cursor_img[i + 1] as int;
                    if (a != 0) {
                        let g = cursor_img[i] as int;
                        let o = yy * fb_w + xx;
                        bb[o] = mix(bb[o] as int, g * 0x010101, (a * 256) / 255) as u32;
                    }
                }
                c++;
            }
        }
        r++;
    }
}
""" % (len(data), "\n".join(rows))
open("kernel/cursor.kc", "w").write(src)
Image.new("RGB", (W * 3 * 4, H * 4), (60, 120, 160))
bg = Image.new("RGB", (W * 3, H), (0xEC, 0xEF, 0xF4)); bg2 = Image.new("RGB", (W * 3, H), (0x0B, 0x10, 0x1E))
for k, im in enumerate((arrow, hand, beam)):
    bg.paste(im.convert("RGB"), (k * W, 0), im.split()[3]); bg2.paste(im.convert("RGB"), (k * W, 0), im.split()[3])
prev = Image.new("RGB", (W * 3, H * 2)); prev.paste(bg, (0, 0)); prev.paste(bg2, (0, H))
prev.resize((W * 3 * 8, H * 2 * 8), Image.NEAREST).save("/tmp/claude-0/-home-claude/77bd19dd-6b21-52db-8b74-85c437d607c1/scratchpad/cursors.png")
print("bytes", len(data))
