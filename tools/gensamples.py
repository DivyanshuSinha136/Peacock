#!/usr/bin/env python3
"""gensamples.py -- regenerate kernel/samples.kc (the example apps seeded into /apps).  Format: see kernel/builder.kc."""
INK=0x1B2433; BLUE=0x1F6FEB; GREEN=0x27AE60; RED=0xE74C3C; ORANGE=0xF39C12; PURPLE=0x8E44AD; WHITE=0xFFFFFF; SOFT=0xDCE6FA; GREY=0xECEFF4
def W(kind,x,y,w,h,col,act=0,tgt=-1,hid=0,text="",arg=""): return f"W|{kind}|{x}|{y}|{w}|{h}|{col}|{act}|{tgt}|{hid}|{text}|{arg}\n"
def app(title,w,h,bg,ws): return f"APP|{title}|{w}|{h}|{bg}\n"+"".join(ws)
keys=[W(5,16,12,188,48,WHITE), W(1,24,20,176,32,BLUE,hid=2,text="")]
for i,d in enumerate("123456789"):
    keys.append(W(2,16+(i%3)*64,70+(i//3)*44,56,36,SOFT,11,1,0,d,d))
keys.append(W(2,16,202,120,36,SOFT,11,1,0,"0","0")); keys.append(W(2,144,202,56,36,RED,5,1,0,"C",""))
samples={
 "counter": app("counter",260,170,GREY,[
   W(1,20,14,220,20,INK,text="Click the buttons:"), W(5,20,44,220,56,WHITE), W(1,30,56,200,32,BLUE,hid=2,text="0"),
   W(2,20,114,70,32,GREEN,2,2,0,"+1","1"), W(2,100,114,70,32,RED,2,2,0,"-1","-1"), W(2,180,114,60,32,ORANGE,1,2,0,"Reset","0")]),
 "adder": app("adder",300,170,SOFT,[
   W(1,20,14,260,20,INK,text="Add two numbers (Enter works too)"),
   W(3,20,44,100,28,INK,12,5,0,"12","1+3"), W(1,128,50,16,20,INK,text="+"), W(3,150,44,100,28,INK,12,5,0,"30","1+3"),
   W(2,20,90,60,32,BLUE,12,5,0,"=","1+3"), W(1,96,90,190,32,PURPLE,hid=2,text="...")]),
 "greeter": app("greeter",300,190,SOFT,[
   W(1,20,14,260,20,INK,text="What is your name?"), W(3,20,40,180,28,INK,4,3,0,"","1"),
   W(2,210,40,70,28,BLUE,4,3,0,"Greet","1"), W(1,20,92,260,24,PURPLE,text="..."), W(4,20,134,200,22,BLUE,6,3,0,"Hide the greeting")]),
 "keypad": app("keypad",220,252,GREY,keys),
 "progress": app("progress",280,150,GREY,[
   W(1,20,14,240,20,INK,text="Progress bar demo"), W(6,20,46,240,18,GREEN,0,-1,0,"30"),
   W(2,20,84,100,32,GREEN,2,1,0,"+10","10"), W(2,140,84,100,32,RED,2,1,0,"-10","-10")]),
 "launcher": app("launcher",260,200,GREY,[
   W(1,20,14,220,20,INK,text="Quick launcher"), W(2,20,44,100,32,BLUE,8,-1,0,"Notes","notes"), W(2,130,44,100,32,GREEN,8,-1,0,"Paint","paint"),
   W(2,20,86,100,32,ORANGE,8,-1,0,"Calc","calc"), W(2,130,86,100,32,PURPLE,8,-1,0,"Terminal","terminal"), W(2,20,138,210,32,RED,10,-1,0,"Close launcher")]),
}
out='// samples.kc -- example apps written with the App Builder, seeded into /apps on first boot.  (generated by tools/gensamples.py)\n\nfn bld_seed_apps() {\n    if (fs_resolve("/apps") >= 0) { return; }\n    fs_create("/apps", K_DIR);\n'
for n,t in samples.items():
    esc=t.replace("\\","\\\\").replace('"','\\"').replace("\n","\\n")
    out+=f'    fs_put_file("/apps/{n}.pea", "{esc}");\n'
out+="}\n"
open('kernel/samples.kc','w').write(out)
