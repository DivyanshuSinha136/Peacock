#!/usr/bin/env python3
"""Convert TrueType/OpenType fonts to SVG fonts (assets/fonts/*.svg, the SVG 1.1 <font> format, y-up em units) and pack them
into kernel/fontdata.kc.  Only printable ASCII (32..126) is kept.  Needs fontTools (build-time only).
Usage: mkfonts.py assets/fonts kernel/fontdata.kc [--regen]"""
import sys, os, re
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

# name, source file, pixel size at which the OS draws it
FONTS = [
    ('Inter',            '/usr/share/fonts/opentype/inter/Inter-Regular.otf', 14),
    ('Poppins',          '/usr/share/fonts/truetype/google-fonts/Poppins-Regular.ttf', 13),
    ('DejaVu Sans',      '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 13),
    ('Liberation Serif', '/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf', 15),
    ('DejaVu Mono',      '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', 13),
]
outdir, outkc = sys.argv[1], sys.argv[2]
regen = '--regen' in sys.argv

def fname(n): return re.sub(r'[^a-z0-9]+', '-', n.lower()).strip('-') + '.svg'

def esc(ch):
    return '&#%d;' % ord(ch)

for name, path, px in FONTS:
    out = os.path.join(outdir, fname(name))
    if os.path.exists(out) and not regen:
        continue
    f = TTFont(path)
    gs = f.getGlyphSet(); cmap = f.getBestCmap()
    upem = f['head'].unitsPerEm
    hhea = f['hhea']
    k = 1000.0 / upem                      # normalise to 1000 units per em
    parts = [f"<svg xmlns='http://www.w3.org/2000/svg'><defs><font id='f' horiz-adv-x='600'>",
             f"<font-face font-family='{name}' units-per-em='1000' ascent='{round(hhea.ascent*k)}' descent='{round(-hhea.descent*k)}'/>"]
    for cp in range(32, 127):
        gn = cmap.get(cp)
        if gn is None: continue
        pen = SVGPathPen(gs, ntos=lambda v: str(int(round(v))))
        gs[gn].draw(TransformPen(pen, (k, 0, 0, k, 0, 0)))
        d = pen.getCommands()
        adv = round(gs[gn].width * k)
        parts.append(f"<glyph unicode='{esc(chr(cp))}' horiz-adv-x='{adv}' d='{d}'/>")
    parts.append("</font></defs></svg>\n")
    open(out, 'w').write(''.join(parts))
    print('wrote', out, os.path.getsize(out), 'bytes')

lines = ["// fontdata.kc -- GENERATED by tools/mkfonts.py from assets/fonts/*.svg (SVG fonts). Do not edit.", ""]
lines.append("const VF_N = %d;" % len(FONTS))
lines.append("fn vf_name(i: int) -> *u8 {")
for i, (name, _, px) in enumerate(FONTS):
    lines.append(f'    if (i == {i}) {{ return "{name}"; }}')
lines.append('    return "";\n}')
lines.append("/// pixel size at which the font is drawn in the UI (equal visual size across faces)")
lines.append("fn vf_px(i: int) -> int {")
for i, (name, _, px) in enumerate(FONTS):
    lines.append(f'    if (i == {i}) {{ return {px}; }}')
lines.append('    return 14;\n}')
lines.append("fn vf_src(i: int) -> *u8 {")
for i, (name, _, px) in enumerate(FONTS):
    s = open(os.path.join(outdir, fname(name))).read()
    s = re.sub(r'\s+', ' ', s).strip()
    assert '"' not in s and '\\' not in s
    lines.append(f'    if (i == {i}) {{ return "{s}"; }}')
lines.append('    return "";\n}')
open(outkc, 'w').write("\n".join(lines) + "\n")
print('mkfonts:', len(FONTS), 'fonts ->', outkc, os.path.getsize(outkc), 'bytes')
